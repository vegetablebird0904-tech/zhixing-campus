'use strict';
// Local desktop lifecycle helper. No startup tasks, firewall rules or system services.
const fs=require('node:fs'),fsp=require('node:fs/promises'),path=require('node:path');
const {spawn}=require('node:child_process');
const os=require('node:os');
const {version}=require('../package.json');
const {instanceIdentity,assertReusable,openBrowser}=require('./launch');
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));

function config(env=process.env){
 const port=Number(env.PORT||3219);
 if(!Number.isInteger(port)||port<1024||port>65535)throw new Error('PORT应为1024-65535');
 const root=path.resolve(__dirname,'..'),dataRoot=env.CAMPUS_DATA_DIR?path.resolve(env.CAMPUS_DATA_DIR):null;
 const data=dataRoot||path.join(__dirname,'storage');
 const lanConfigFile=env.CAMPUS_LAN_CONFIG_FILE?path.resolve(env.CAMPUS_LAN_CONFIG_FILE):path.join(root,'utils','lan-config.js');
 const serviceConfigFile=env.CAMPUS_SERVICE_CONFIG_FILE?path.resolve(env.CAMPUS_SERVICE_CONFIG_FILE):path.join(root,'data','service-config.js');
 return {root,data,dataRoot,port,base:'http://127.0.0.1:'+port,instanceId:instanceIdentity(__dirname,dataRoot),
  record:path.join(data,'service-process.json'),log:path.join(data,'logs','service.log'),script:path.join(__dirname,'launch.js'),lanConfigFile,serviceConfigFile};
}
function privateIPv4(value){
 if(!/^\d{1,3}(?:\.\d{1,3}){3}$/.test(String(value||'')))return false;
 const octets=String(value||'').split('.').map(Number);
 if(octets.length!==4||octets.some(n=>!Number.isInteger(n)||n<0||n>255))return false;
 return octets[0]===10||octets[0]===192&&octets[1]===168||octets[0]===172&&octets[1]>=16&&octets[1]<=31;
}
function lanEndpoints(port,interfaces=os.networkInterfaces()){
 const entries=[];
 for(const [name,records] of Object.entries(interfaces||{}))for(const item of records||[]){
  if(item&&item.family==='IPv4'&&!item.internal&&privateIPv4(item.address)){
   const wifi=/wi-?fi|wlan|wireless|无线/i.test(name);
   entries.push({url:'http://'+item.address+':'+port,wifi,name});
  }
 }
 entries.sort((a,b)=>Number(b.wifi)-Number(a.wifi)||a.name.localeCompare(b.name)||a.url.localeCompare(b.url));
 return [...new Set(entries.map(item=>item.url))];
}
async function writeLanConfig(root,endpoints,targetFile,metadata={}){
 const file=targetFile||path.join(root,'utils','lan-config.js');
 let previous={};
 try{const resolved=require.resolve(file);delete require.cache[resolved];previous=require(resolved);}catch{}
 const current=new Set(endpoints),previousEndpoints=[...new Set([...(previous.previousEndpoints||[]),...(previous.endpoints||[])])].filter(value=>!current.has(value));
 const contents="'use strict';\n// Generated by the phone-test launcher. Contains only private LAN addresses.\nmodule.exports = "+JSON.stringify({endpoints,previousEndpoints,instanceId:metadata.instanceId||previous.instanceId||'',generatedAt:new Date().toISOString()},null,2)+';\n';
 const temp=file+'.'+process.pid+'.tmp';
 await fsp.mkdir(path.dirname(file),{recursive:true});
 await fsp.writeFile(temp,contents,{encoding:'utf8',mode:0o600});
 await fsp.rename(temp,file);
 const serviceFile=metadata.serviceConfigFile||path.join(root,'data','service-config.js');
 await fsp.mkdir(path.dirname(serviceFile),{recursive:true});
 const service="'use strict';\n// Generated local connection metadata; no credentials.\nmodule.exports="+JSON.stringify({app:'zhixing-campus',instanceId:metadata.instanceId||'',endpoints,generatedAt:new Date().toISOString()})+';\n';
 const serviceTemp=serviceFile+'.'+process.pid+'.tmp';await fsp.writeFile(serviceTemp,service,{encoding:'utf8',mode:0o600});await fsp.rename(serviceTemp,serviceFile);
 return endpoints;
}
async function health(c){
 for(let attempt=0;attempt<2;attempt++){
 try{
  const r=await fetch(c.base+'/api/health',{headers:{Connection:'close'},signal:AbortSignal.timeout(1000)});
  if(!r.ok)throw new Error('HTTP '+r.status);
  return await r.json();
 }catch(error){
  const code=error.cause?.code||error.code;
  if(code==='ECONNREFUSED')return null;
  if(attempt===0&&['ECONNRESET','UND_ERR_SOCKET','EPIPE'].includes(code)){await delay(100);continue;}
  throw new Error('端口有响应但不是可确认的校园服务，或连接超时；不会结束未知进程。'+error.message);
 }
 }
}
async function readRecord(c){try{return JSON.parse(await fsp.readFile(c.record,'utf8'));}catch(e){if(e.code==='ENOENT')return null;throw new Error('服务记录损坏，已保留原文件：'+c.record);}}
function owned(c,record,current){
 return !!(record&&current&&current.app==='zhixing-campus'&&current.managed===true&&
  current.instanceId===c.instanceId&&record.instanceId===c.instanceId&&record.pid===current.pid&&
  record.bootId===current.bootId&&path.resolve(record.script||'')===c.script);
}
async function replaceFile(file,contents){
 const tmp=file+'.'+process.pid+'.'+Date.now()+'.tmp';
 await fsp.writeFile(tmp,contents,{encoding:'utf8',mode:0o600});
 try{await fsp.rename(tmp,file);}catch(error){
  // Windows may refuse replacement when a stale destination is present. Keep the old record until the new one is durable.
  if(!['EEXIST','EPERM','EACCES'].includes(error.code))throw error;
  const backup=file+'.'+process.pid+'.bak';
  try{await fsp.rename(file,backup);}catch(moveError){if(moveError.code!=='ENOENT')throw moveError;}
  try{await fsp.rename(tmp,file);await fsp.rm(backup,{force:true});}
  catch(replaceError){try{await fsp.rename(backup,file);}catch{}throw replaceError;}
 }finally{await fsp.rm(tmp,{force:true});}
}
async function writeRecord(c,value){await replaceFile(c.record,JSON.stringify(value,null,2));}
async function ready(c,child,errorState,timeout=15000){
 const start=Date.now();
 while(Date.now()-start<timeout){
  if(errorState.error)throw errorState.error;
  if(child.exitCode!==null)throw new Error('服务在启动完成前退出（'+child.exitCode+'）');
  const h=await health(c);
  if(h){
   if(h.app!=='zhixing-campus'||h.version!==version||h.instanceId!==c.instanceId||h.pid!==child.pid)throw new Error('端口被另一服务占用，未打开管理端');
   const authResponse=await fetch(c.base+'/api/auth/status',{signal:AbortSignal.timeout(1500)});
   const auth=await authResponse.json();
   if(!authResponse.ok||auth.app!=='zhixing-campus'||!auth.enabled)throw new Error('账号接口尚未就绪');
   return h;
  }
  await delay(150);
 }
 throw new Error('服务启动超时');
}
async function start(c,{mode='local',browser=true,repair=false}={}){
 if(process.env.NODE_ENV==='production')throw new Error('此一键启动器用于本机开发。生产模式请使用已配置HTTPS的server/launch.js与正式进程管理服务，不会关闭HTTPS检查。');
 if(!['local','lan'].includes(mode))throw new Error('mode仅支持local或lan');
 const host=mode==='lan'?'0.0.0.0':'127.0.0.1';
 const requestedEndpoints=mode==='lan'?lanEndpoints(c.port):[];
 if(mode==='lan'&&!requestedEndpoints.length)throw new Error('未检测到电脑私有局域网IPv4地址；请先连接Wi-Fi或有线局域网，再启动手机联调服务。');
 let current=await health(c);
 if(repair&&current&&(current.version!==version||mode==='lan'&&!['0.0.0.0','::'].includes(current.listenHost))){
  if(!owned(c,await readRecord(c),current))throw new Error('检测到仅监听本机的其他服务，不会停止它。请关闭对应目录的服务后重试');
  console.log('将本目录管理的本机服务切换为手机联调模式，账号与业务数据保留。');
  await stop(c);current=null;
 }
 if(current){
  assertReusable(current,{host,instanceId:c.instanceId});
  console.log('服务已在运行，无需重复启动。PID：'+current.pid);
 }else{
  await writeLanConfig(c.root,requestedEndpoints,c.lanConfigFile,{instanceId:c.instanceId,serviceConfigFile:c.serviceConfigFile});
  await fsp.mkdir(path.dirname(c.log),{recursive:true});
  const log=fs.openSync(c.log,'a',0o600),errorState={error:null};let child;
  try{
   fs.writeSync(log,'\n--- '+new Date().toISOString()+' v'+version+' '+mode+' ---\n');
   child=spawn(process.execPath,[c.script],{cwd:c.root,detached:true,windowsHide:true,
    stdio:['ignore',log,log],env:{...process.env,PORT:String(c.port),...(c.dataRoot?{CAMPUS_DATA_DIR:c.dataRoot}:{}),CAMPUS_HOST:host,CAMPUS_NO_BROWSER:'1',CAMPUS_MANAGED:'1'}});
   child.once('error',e=>{errorState.error=e;});
  }finally{fs.closeSync(log);}
  child.unref();
  try{
   current=await ready(c,child,errorState);
   await writeRecord(c,{pid:child.pid,instanceId:c.instanceId,bootId:current.bootId,script:c.script,host,port:c.port,version,startedAt:new Date().toISOString()});
  }catch(error){
   // This handle is exclusively the process created above, never an arbitrary PID.
   if(child.exitCode===null&&!child.killed)child.kill();
   throw new Error(error.message+'。启动日志：'+c.log);
  }
 }
 const servingLan=['0.0.0.0','::'].includes(current.listenHost);
 const phoneAddresses=await writeLanConfig(c.root,servingLan?lanEndpoints(c.port):[],c.lanConfigFile,{instanceId:c.instanceId,serviceConfigFile:c.serviceConfigFile});
 console.log('后台服务已就绪 · v'+current.version+'\n管理端：'+c.base+'/admin/\n关闭本窗口或浏览器不会停止后台服务。\n停止服务请运行“停止校园服务.cmd”。\n日志：'+c.log);
 if(servingLan)for(const a of phoneAddresses)console.log('手机服务地址：'+a);
 const status=await fetch(c.base+'/api/auth/status',{signal:AbortSignal.timeout(1500)}).then(r=>r.json());
 if(status.setupNeeded)console.log('首次管理员设置码文件：'+path.join(c.data,'auth','首次管理员设置码.txt')+'\n仅电脑本机初始化。请自行查看设置码，不要发给普通用户。');
 if(browser)openBrowser((process.env.PUBLIC_BASE_URL||c.base)+'/admin/');
 return current;
}
async function stop(c){
 const current=await health(c),record=await readRecord(c);
 if(!current){await writeLanConfig(c.root,[],c.lanConfigFile,{instanceId:c.instanceId,serviceConfigFile:c.serviceConfigFile});console.log('服务已停止，无需操作。');return;}
 if(!owned(c,record,current))throw new Error('当前服务不是由本目录后台启动器管理，或运行标识不符；不会停止未知进程。请关闭对应的旧版服务窗口。');
 process.kill(record.pid,'SIGTERM');
 for(let i=0;i<50;i++){
  const h=await health(c);
  if(!h){await fsp.rm(c.record,{force:true});await writeLanConfig(c.root,[],c.lanConfigFile,{instanceId:c.instanceId,serviceConfigFile:c.serviceConfigFile});console.log('校园后台服务已停止，账号与业务数据保留。');return;}
  if(h.bootId!==record.bootId)throw new Error('端口已被其他服务接管，不再执行停止操作');
  await delay(100);
 }
 throw new Error('停止超时，请查看服务状态；不会重试结束其他进程。');
}
async function status(c){
 const h=await health(c);
 if(!h){console.log('服务未运行。请在Windows文件资源管理器中双击“打开管理端.cmd”；在微信编辑器内打开文件不会运行它。');return null;}
 console.log('服务运行中：v'+h.version+'，PID '+h.pid+'，监听 '+h.listenHost+'\n管理端：'+c.base+'/admin/\n日志：'+c.log);
 return h;
}
async function main(args=process.argv.slice(2)){
 const action=args[0]||'start',c=config();
 if(action==='start'){await fsp.rm(path.join(c.data,'service-paused'),{force:true});return start(c,{mode:args.includes('--lan')?'lan':'local',browser:!args.includes('--no-browser'),repair:args.includes('--repair')});}
 if(action==='stop'){await fsp.mkdir(c.data,{recursive:true});await fsp.writeFile(path.join(c.data,'service-paused'),'paused');return stop(c);}
 if(action==='status')return status(c);
 throw new Error('用法：control.js start [--lan] [--no-browser] | stop | status');
}
if(require.main===module)main().catch(e=>{console.error('启动/连接失败：'+e.message);process.exitCode=1;});
module.exports={config,health,owned,start,stop,status,main,privateIPv4,lanEndpoints,writeLanConfig};
